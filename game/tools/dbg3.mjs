import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { simplify, weld, normals } from '@gltf-transform/functions';
import { MeshoptSimplifier } from 'meshoptimizer';
import draco3d from 'draco3dgltf';
await MeshoptSimplifier.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'draco3d.decoder': await draco3d.createDecoderModule() });
const doc = await io.read('../models/out/ferrari458_lo.glb');
const count = (d) => { let t=0, v=0; for (const m of d.getRoot().listMeshes()) for (const p of m.listPrimitives()) { t += p.getIndices().getCount()/3; v += p.getAttribute('POSITION').getCount(); } return {t, v}; };
console.log('loaded', count(doc));
const prim = doc.getRoot().listMeshes()[0].listPrimitives()[0];
console.log('prim0 sem', prim.listSemantics(), 'mode', prim.getMode(), 'verts', prim.getAttribute('POSITION').getCount(), 'idx', prim.getIndices().getCount());
const pos = prim.getAttribute('POSITION').getArray(); const idx = prim.getIndices().getArray();
const res = MeshoptSimplifier.simplify(idx, pos, 3, Math.floor(idx.length*0.1), 0.05, []);
console.log('direct meshopt simplify ->', res[0].length/3, 'tris from', idx.length/3, 'err', res[1]);
const res2 = MeshoptSimplifier.simplify(idx, pos, 3, Math.floor(idx.length*0.1), 0.05, ['LockBorder']);
console.log('direct meshopt simplify (lock) ->', res2[0].length/3);
await doc.transform(simplify({ simplifier: MeshoptSimplifier, ratio: 0.1, error: 0.05, lockBorder: false }));
console.log('after simplify fn', count(doc));
